def get_next_game_start_time():
    now = datetime.now()
    game_start = datetime(now.year, now.month, now.day, 
                         FIRST_GAME_START_HOUR, FIRST_GAME_START_MINUTE)
    if now < game_start:
        return game_start.timestamp()
    cycle_duration = (GAME_DURATION_HOURS + INTERVAL_BETWEEN_GAMES_HOURS) * 3600
    time_passed = (now - game_start).total_seconds()
    cycles_passed = int(time_passed // cycle_duration)
    next_start = game_start + timedelta(seconds=(cycles_passed + 1) * cycle_duration)
    return next_start.timestamp()

